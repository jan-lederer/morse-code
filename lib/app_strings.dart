  static String tr(String text) {
    if (text.startsWith('Practice set: ')) {
      return '${_translations[language]?['Practice set:'] ?? 'Practice set:'} ${tr(text.substring(14))}';
    }
    if (language != 'EN' && text.startsWith('Correct! It’s ')) {
      final target = text
          .substring('Correct! It’s '.length)
          .replaceFirst('. Next letter…', '');
      return switch (language) {
        'DE' => 'Richtig! $target. Nächster Buchstabe…',
        'FR' => 'Correct ! $target. Lettre suivante…',
        'ES' => '¡Correcto! $target. Siguiente letra…',
        _ => text,
      };
    }
    if (language == 'DE') {
      final count = RegExp(r'^(\d+) characters$').firstMatch(text);
      if (count != null) return '${count[1]} Zeichen';
      final mastery = text
          .replaceFirst(
            'Current practice set proficiency: green',
            'Übungsfortschritt: grün',
          )
          .replaceFirst(', yellow ', ', gelb ')
          .replaceFirst(', red ', ', rot ');
      if (mastery != text) return mastery;
      final score = RegExp(r'^(\d+) / (\d+) correct$').firstMatch(text);
      if (score != null) return '${score[1]} / ${score[2]} richtig';
      if (text.startsWith('Version ')) return text;
    }
    if (language == 'FR') {
      final count = RegExp(r'^(\d+) characters$').firstMatch(text);
      if (count != null) return '${count[1]} caractères';
      final score = RegExp(r'^(\d+) / (\d+) correct$').firstMatch(text);
      if (score != null) return '${score[1]} / ${score[2]} corrects';
      if (text.startsWith('Version ')) return text;
    }
    if (language == 'ES') {
      final count = RegExp(r'^(\d+) characters$').firstMatch(text);
      if (count != null) return '${count[1]} caracteres';
      final score = RegExp(r'^(\d+) / (\d+) correct$').firstMatch(text);
      if (score != null) return '${score[1]} / ${score[2]} correctas';
      if (text.startsWith('Version ')) {
        return text.replaceFirst('Version', 'Versión');
      }
    }
    return _translations[language]?[text] ?? text;
  }

